// Function to get random dialogue set for a level
export function getRandomDialogue(level) {
  const levelDialogues = DIALOGUES[level] || DIALOGUES[1];
  const randomIndex = Math.floor(Math.random() * levelDialogues.length);
  return levelDialogues[randomIndex];
}